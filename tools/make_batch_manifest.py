"""Batch manifest for CVAT ground-truth review: a stratified, reproducible sample of Training clips.

    python tools/make_batch_manifest.py --batch 1 --n 20 --seed 42

Strata = accident type x source (4 strata, equal quota). Clips that already have human-reviewed labels are
always included (they anchor the batch), then the rest of each stratum's quota is drawn at random with the
seed, without looking at any engine result (so the batch is not biased towards easy or failing clips).
At least `--min-night` night clips are guaranteed. Validation and Test clips are never selected.
Writes experiments/batches/batch_<n>.csv and .md.
"""
import argparse, csv, json, random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ITEMS = ["vehicle_b", "collision_frame", "lane_change", "sudden_stop", "safe_distance", "vehicle_boxes", "lane_lines"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--batch", type=int, default=1)
    ap.add_argument("--n", type=int, default=20)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--min-night", type=int, default=2)
    ap.add_argument("--index", default=str(ROOT / "experiments" / "dataset" / "dataset_index.csv"))
    ap.add_argument("--job-map", default=str(ROOT / "experiments" / "dataset" / "clip_job_map_v2.csv"))
    a = ap.parse_args()
    rows = [r for r in csv.DictReader(open(a.index)) if r["split"] == "train"]
    jobs = {r["clip_id"]: r for r in csv.DictReader(open(a.job_map))}
    human = json.loads((ROOT / "experiments" / "ground_truth" / "human_reviewed.json").read_text())["clips"]
    rng = random.Random(a.seed)
    strata = {}
    for r in rows:
        strata.setdefault((r["accident_type"], r["source"]), []).append(r)
    quota = a.n // len(strata)
    chosen = []
    for k in sorted(strata):
        pool = sorted(strata[k], key=lambda r: r["clip_id"])
        fixed = [r for r in pool if r["clip_id"] in human]
        rest = [r for r in pool if r["clip_id"] not in human]
        rng.shuffle(rest)
        chosen += (fixed + rest)[:max(quota, len(fixed))]
    night = [r for r in chosen if r["time_of_day"] == "Night"]
    if len(night) < a.min_night:                      # swap in night clips from the same stratum
        for r in sorted(rows, key=lambda r: r["clip_id"]):
            if len([x for x in chosen if x["time_of_day"] == "Night"]) >= a.min_night:
                break
            if r["time_of_day"] == "Night" and r not in chosen:
                same = [x for x in chosen if (x["accident_type"], x["source"]) == (r["accident_type"], r["source"])
                        and x["clip_id"] not in human and x["time_of_day"] != "Night"]
                if same:
                    chosen[chosen.index(same[-1])] = r
    out_dir = ROOT / "experiments" / "batches"
    out_dir.mkdir(parents=True, exist_ok=True)
    F = ["batch", "clip_id", "accident_type", "source", "time_of_day", "crash_start_frame", "num_frames", "cvat_task",
         "cvat_job_in_task", "annotator", "reviewer", "gt_status", "approved_items", "items_to_review"]
    recs = []
    for r in sorted(chosen, key=lambda r: (r["accident_type"], r["source"], r["clip_id"])):
        h = human.get(r["clip_id"], {})
        done = [i for i in ITEMS if i in h or (i == "collision_frame" and "collision_frame" in h)]
        todo = [i for i in ITEMS if i not in done]
        j = jobs.get(r["clip_id"], {})
        recs.append({"batch": a.batch, "clip_id": r["clip_id"], "accident_type": r["accident_type"], "source": r["source"],
                     "time_of_day": r["time_of_day"], "crash_start_frame": r["crash_start_frame"], "num_frames": r["num_frames"],
                     "cvat_task": j.get("task", ""), "cvat_job_in_task": j.get("job_number_in_task", ""),
                     "annotator": j.get("annotator", ""), "reviewer": j.get("reviewer", ""),
                     "gt_status": "Partially approved" if done else "Needs review",
                     "approved_items": "; ".join(done), "items_to_review": "; ".join(todo)})
    with open(out_dir / f"batch_{a.batch}.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=F); w.writeheader(); w.writerows(recs)
    L = [f"# Batch {a.batch} — CVAT ground-truth review ({len(recs)} Training clips)", "",
         f"Selection: stratified by accident type × source ({quota} per stratum), seed {a.seed}, clips with existing human review always included, "
         f"at least {a.min_night} night clips; no engine result was used to choose clips. Generated by `tools/make_batch_manifest.py`.", "",
         "| # | Clip | Type | Source | Time | CVAT task / job | Annotator → reviewer | GT status | Approved | To review |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(recs, 1):
        L.append(f"| {i} | `{r['clip_id']}` | {r['accident_type']} | {r['source']} | {r['time_of_day']} | {r['cvat_task']} / {r['cvat_job_in_task']} | "
                 f"{r['annotator']} → {r['reviewer']} | {r['gt_status']} | {r['approved_items'] or '—'} | {r['items_to_review']} |")
    from collections import Counter
    c = Counter((r["accident_type"], r["source"]) for r in recs)
    L += ["", "Composition: " + ", ".join(f"{t} {s}: {n}" for (t, s), n in sorted(c.items())) +
          f"; night: {sum(r['time_of_day'] == 'Night' for r in recs)}; partially approved: {sum(r['gt_status'] != 'Needs review' for r in recs)}; "
          f"needs review: {sum(r['gt_status'] == 'Needs review' for r in recs)}."]
    (out_dir / f"batch_{a.batch}.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
